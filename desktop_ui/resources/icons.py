def get_icon(name: str, color: str = "#94A3B8", size: int = 24) -> QIcon:
    """Render a vector SVG template to a crisp QIcon with the specified color."""
    template = SVG_TEMPLATES.get(name)
    if not template:
        return QIcon()

    svg_content = template.format(color=color)
    renderer = QSvgRenderer(QByteArray(svg_content.encode("utf-8")))

    # Render at 2x for crisp Retina/HiDPI display
    scale = 2
    pixmap = QPixmap(size * scale, size * scale)
    pixmap.fill(QColor(0, 0, 0, 0))

    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()

    return QIcon(pixmap)


def get_pixmap(name: str, color: str = "#94A3B8", size: int = 24) -> QPixmap:
    """Render a vector SVG template to a QPixmap."""
    template = SVG_TEMPLATES.get(name)
    if not template:
        return QPixmap(size, size)

    svg_content = template.format(color=color)
    renderer = QSvgRenderer(QByteArray(svg_content.encode("utf-8")))

    scale = 2
    pixmap = QPixmap(size * scale, size * scale)
    pixmap.fill(QColor(0, 0, 0, 0))

    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()

    return pixmap
